--- Permission values of the admin plugin: `PERM_ALLOW`, `PERM_NO`, `PERM_NEVER`,
-- `PERM_ALLOW_OVERRIDE` and `PERM_ERROR`.
-- A player's individual and temporary permissions hold `PERM_ALLOW` (always allowed),
-- `PERM_NEVER` (always denied) or `PERM_NO` (not set, the player's role decides). The
-- last two values are not used by the plugin itself.

enumerate 'PERM_ALLOW PERM_NO PERM_NEVER PERM_ALLOW_OVERRIDE PERM_ERROR'
