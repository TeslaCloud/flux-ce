--- Environment variables of Flux: the `ENV` table with `getenv` and `setenv`, and the
-- `FLUX_ENV` variable that names the environment Flux runs in.
-- Both entry points of the gamemode include this file first. On the first boot it reads
-- `FLUX_ENV` from `config/environment.local.lua` if that file exists, else from
-- `config/environment.lua`, and falls back to 'development' when the file returns nothing.
-- The server shares variables with clients through `add_client_env`, which appends `setenv`
-- calls to the generated `lua/_flux/environment.lua` file that clients include here.

AddCSLuaFile()

ENV = ENV or {}

if !getenv then
  --- Gets an environment variable matching the "key" name.
  -- @param key [String variable name]
  -- @param default=nil [Any value to return if the variable is not set]
  -- @return [Any environment variable, or default if it is not set]
  function getenv(key, default)
    local res = ENV[key]

    if res != nil then
      return res
    end

    return default
  end
end

if !setenv then
  --- Sets an environment variable "key" to "value".
  -- @param key [String variable name]
  -- @param value [Any new value]
  -- @return [Any the new value]
  function setenv(key, value)
    ENV[key] = value
    return ENV[key]
  end
end

do
  local client_vars = {}

  --- Adds an environment variable to the clientside environment variables list.
  -- Only the first call for a key has an effect. Key and value are converted to strings.
  -- Serverside only, does nothing on the client.
  -- @param key [String variable name]
  -- @param value [String variable value]
  function add_client_env(key, value)
    if SERVER and !client_vars[key] then
      client_vars[key] = true
      File.append(
        'lua/_flux/environment.lua',
        'setenv('..string.format('%q', tostring(key))..', '..string.format('%q', tostring(value))..')\n'
      )
    end
  end
end

if Flux and Flux.initialized then return end

FLUX_ENV_PATH = file.Exists('flux/config/environment.local.lua', 'LUA') ? 'flux/config/environment.local.lua' :
  'flux/config/environment.lua'
setenv('FLUX_ENV', string.lower(include(FLUX_ENV_PATH) or 'development'))

if CLIENT then
  include '_flux/environment.lua'
else
  File.write(
    'lua/_flux/environment.lua',
    '--\n-- This file is automatically generated.\n-- Do not edit this file manually!\n--\n\n'
  )
end
