--- Environment variables of Flux: the `ENV` table with `getenv` and `setenv`, the `FLUX_ENV`
-- variable that names the environment Flux runs in and `IS_TASK`, which tells whether Flux runs
-- as a task of fpkg.
-- `lib/start.lua` includes this file first. On the first boot it reads `FLUX_ENV` from the
-- first file that exists of `config/environment.local.lua` and `config/environment.lua` of the
-- schema's gamemode folder and `config/environment.lua` of the Flux package (see
-- `find_config_file`), and falls back to 'development' when the file returns nothing; in a task
-- the `--env` flag of fpkg wins over the file. Any name other than 'development', 'production'
-- and 'test' stops the boot with an error. `FLUX_ENV_PATH` holds the path of that file.
-- The server shares variables with clients through `add_client_env`, which appends `setenv`
-- calls to the generated `lua/_flux/environment.lua` file that clients include here. Tasks
-- never write that file, which belongs to the game server.

AddCSLuaFile()

ENV = ENV or {}

--- Whether Flux runs as a task of fpkg (`fpkg db:migrate`), in fpkg's runtime without the game
-- server, rather than in the game: true when the `fpkg` global of that runtime exists.
IS_TASK = istable(fpkg)

if !getenv then
  --- Gets an environment variable matching the "key" name.
  -- @param key [String variable name]
  -- @param default=nil [Any value to return if the variable is not set]
  -- @return [Any environment variable, or default if it is not set]
  function getenv(key, default)
    local res = ENV[key]

    if res != nil then
      return res
    end

    return default
  end
end

if !setenv then
  --- Sets an environment variable "key" to "value".
  -- @param key [String variable name]
  -- @param value [Any new value]
  -- @return [Any the new value]
  function setenv(key, value)
    ENV[key] = value
    return ENV[key]
  end
end

if !add_client_env then
  local client_vars = {}

  --- Adds an environment variable to the clientside environment variables list.
  -- Only the first call for a key has an effect, also across code refreshes. Key and value are
  -- converted to strings. Serverside only, does nothing on the client and in fpkg's tasks.
  -- @param key [String variable name]
  -- @param value [String variable value]
  function add_client_env(key, value)
    if SERVER and !IS_TASK and !client_vars[key] then
      client_vars[key] = true
      File.append(
        'lua/_flux/environment.lua',
        'setenv('..string.format('%q', tostring(key))..', '..string.format('%q', tostring(value))..')\n'
      )
    end
  end
end

--- Finds a configuration file. The server's own config lives in the `config` folder of the
-- schema's gamemode and replaces the file that ships with Flux, file by file: the first that
-- exists of `<name>.local.<ext>` and `<name>.<ext>` there is used, else the file of the same
-- name in the `config` folder of the Flux package.
-- ```
-- find_config_file('environment.lua', 'LUA') -- 'hl2rp/config/environment.lua'
-- ```
-- @param file_name [String name of the file with its extension, such as 'database.yml']
-- @param path_id='GAME' [String 'GAME' for a path relative to the game folder, 'LUA' for one
--   relative to the Lua search path]
-- @return [String path of the file]
function find_config_file(file_name, path_id)
  path_id = path_id or 'GAME'

  local root = path_id == 'GAME' ? 'gamemodes/' : ''
  local folder = root..engine.ActiveGamemode()..'/config/'
  local local_name = file_name:gsub('(%.[^.]+)$', '.local%1')

  if file.Exists(folder..local_name, path_id) then
    return folder..local_name
  elseif file.Exists(folder..file_name, path_id) then
    return folder..file_name
  end

  return root..FLUX_PATH..'config/'..file_name
end

if Flux and Flux.initialized then return end

FLUX_ENV_PATH = find_config_file('environment.lua', 'LUA')

do
  local flag = IS_TASK and fpkg.env
  local environment = string.lower(flag or include(FLUX_ENV_PATH) or 'development')

  if environment != 'development' and environment != 'production' and environment != 'test' then
    error('Unknown environment "'..environment..'" '..(flag ? 'given with --env! Give' : 'returned by '
      ..FLUX_ENV_PATH..'! Return')..' "development", "production" or "test".', 0)
  end

  setenv('FLUX_ENV', environment)
end

if CLIENT then
  include '_flux/environment.lua'
elseif !IS_TASK then
  File.write(
    'lua/_flux/environment.lua',
    '--\n-- This file is automatically generated.\n-- Do not edit this file manually!\n--\n\n'
  )
end
